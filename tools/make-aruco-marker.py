"""Print a marker that OpenCV will actually recognise, with the label on the paper.

    python tools/make-aruco-marker.py                        # DICT_4X4_50, id 7
    python tools/make-aruco-marker.py --dict DICT_4X4_50 --id 12
    python tools/make-aruco-marker.py --cm 8 --out ~/Desktop/marker.png

Why this exists: a marker was printed from some generator and no OpenCV dictionary would
decode it. The bit pattern was structurally fine - 6x6 data with a black border, outer ring
all black - but it matched no id in any of the nineteen dictionaries, while a marker
generated by OpenCV matched its own id with zero bits wrong. So the generator, not the print,
was the problem.

A marker printed from here cannot have that problem, because the image and the dictionary are
made by the same library that will read it. The label is part of the sheet on purpose: the
dictionary and id are the two things needed to configure the reader, and losing them is how
this gets confusing later.

Sizing matters more than anything else in practice. A DICT_4X4_* marker is 6x6 cells, so each
cell needs about 4 px to be sampled reliably: the marker should be at least 40 px across in
the camera image, ideally 60. Measure the printed marker once in a frame before trusting it;
tests/aruco_check.py does exactly that.
"""

from __future__ import annotations

import argparse
import os
import sys

import cv2
import numpy as np

ARUCO = cv2.aruco

# Quiet zone in cells of the marker. One is the minimum below which detection is unreliable;
# two costs nothing on paper and survives a sloppy cut.
QUIET_CELLS = 2


def families() -> list[str]:
    return sorted(d for d in dir(ARUCO) if d.startswith("DICT_") and d.upper() == d)


def make(dict_name: str, marker_id: int, side_px: int) -> np.ndarray:
    dictionary = ARUCO.getPredefinedDictionary(getattr(ARUCO, dict_name))
    cells = dictionary.markerSize + 2
    marker = ARUCO.generateImageMarker(dictionary, marker_id, side_px)
    quiet = side_px // cells * QUIET_CELLS
    return cv2.copyMakeBorder(marker, quiet, quiet, quiet, quiet,
                              cv2.BORDER_CONSTANT, value=255)


def sheet(marker: np.ndarray, dict_name: str, marker_id: int, cm: float) -> np.ndarray:
    """The marker plus a caption, so the paper says what it is."""
    image = cv2.cvtColor(marker, cv2.COLOR_GRAY2BGR)
    cells = int(round(marker.shape[0] / 1.0))
    band = 90
    canvas = np.full((image.shape[0] + band, image.shape[1], 3), 255, np.uint8)
    canvas[band:, :] = image
    font = cv2.FONT_HERSHEY_SIMPLEX
    cv2.putText(canvas, f"{dict_name}  id {marker_id}", (14, 38), font, 0.9, (0, 0, 0), 2)
    cv2.putText(canvas, f"print this page so the BLACK SQUARE is about {cm:g} cm across",
                (14, 70), font, 0.5, (60, 60, 60), 1)
    return canvas


def main() -> int:
    ap = argparse.ArgumentParser(description="Make a marker OpenCV can read")
    ap.add_argument("--dict", dest="dict_name", default="DICT_4X4_50",
                    help="dictionary (default DICT_4X4_50: the smallest one, so the fewest "
                         "false positives). Use --list to see them all")
    ap.add_argument("--id", dest="marker_id", type=int, default=7)
    ap.add_argument("--side-px", type=int, default=1400,
                    help="size of the marker's black square in the image (default 1400)")
    ap.add_argument("--cm", type=float, default=7.0,
                    help="the size you intend to print it at, for the caption (default 7)")
    ap.add_argument("--out", default=os.path.expanduser("~/Desktop/aruco-marker.png"))
    ap.add_argument("--list", action="store_true", help="list the dictionaries and exit")
    args = ap.parse_args()

    if args.list:
        for name in families():
            d = ARUCO.getPredefinedDictionary(getattr(ARUCO, name))
            print(f"  {name:>24}  {d.markerSize}x{d.markerSize} 数据, "
                  f"{d.bytesList.shape[0]} 个 id")
        return 0

    if args.dict_name not in families():
        print(f"error: unknown dictionary {args.dict_name} (--list shows them)",
              file=sys.stderr)
        return 2
    dictionary = ARUCO.getPredefinedDictionary(getattr(ARUCO, args.dict_name))
    count = dictionary.bytesList.shape[0]
    if not 0 <= args.marker_id < count:
        print(f"error: id must be 0..{count - 1} for {args.dict_name}", file=sys.stderr)
        return 2

    marker = make(args.dict_name, args.marker_id, args.side_px)

    # Prove it before handing it over: read it back with the same parameters the checker
    # uses, so a file that fails here is never printed.
    detector = ARUCO.ArucoDetector(dictionary, ARUCO.DetectorParameters())
    _, ids, _ = detector.detectMarkers(marker)
    found = [] if ids is None else [int(x) for x in ids.flatten()]
    if found != [args.marker_id]:
        print(f"error: the marker just generated did not read back (got {found})",
              file=sys.stderr)
        return 1

    out = os.path.abspath(os.path.expanduser(args.out))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    ok = cv2.imwrite(out, sheet(marker, args.dict_name, args.marker_id, args.cm))
    if not ok:
        print(f"error: could not write {out}", file=sys.stderr)
        return 1

    cells = dictionary.markerSize + 2
    print(f"marker  {args.dict_name}  id {args.marker_id}")
    print(f"        读回验证通过 ({found})")
    print(f"        {args.side_px}px 黑方块, 静区 {QUIET_CELLS} 格, 共 {cells} 格")
    print(f"written {out}")
    print()
    print("打印后请做两件事:")
    print(f"  1) 在 800x600 画面里量一下边长: 至少要 40px（每格约 6~7px 才采得准）")
    print(f"     $P tests/aruco_check.py --dict {args.dict_name} --id {args.marker_id}")
    print(f"  2) 别裁掉白边 —— 白边是标记的一部分")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
